  function own(o, k) { return Object.prototype.hasOwnProperty.call(o, k); }

  /* 单模块正文。未知 id → null（明确失败，不回退到其他模块）。 */
  function module(id) {
    if (typeof id !== 'string' || !own(TEXT, id)) return null;
    return TEXT[id];
  }

  /* 场景 → 模块 id 数组。未知场景 → null。返回新数组，调用方改不到内部常量。 */
  function planOf(scene) {
    if (typeof scene !== 'string' || !own(PLANS, scene)) return null;
    return PLANS[scene].slice();
  }

  function fail(scene, error, missing) {
    return Object.freeze({
      ok: false,
      scene: (typeof scene === 'string' ? scene : null),
      error: error,
      missing: Object.freeze(missing || []),
      modules: Object.freeze([]),
      parts: Object.freeze([]),
      text: ''
    });
  }

  /* 场景 → 完整展开。合法场景返回 5 个模块；任一模块正文为空即整体失败。 */
  function forScenario(scene) {
    var plan = planOf(scene);
    if (!plan) return fail(scene, 'unknown-scene', []);
    var ids = [];
    var parts = [];
    for (var i = 0; i < plan.length; i++) {
      var t = module(plan[i]);
      if (typeof t !== 'string' || !t) return fail(scene, 'empty-module', [plan[i]]);
      ids.push(plan[i]);
      parts.push(Object.freeze({ id: plan[i], text: t }));
    }
    return Object.freeze({
      ok: true,
      scene: scene,
      error: null,
      missing: Object.freeze([]),
      modules: Object.freeze(ids),
      parts: Object.freeze(parts),
      text: parts.map(function (p) { return p.text; }).join('\n\n')
    });
  }

