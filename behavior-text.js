  if (own(NS, 'behaviorText')) {
    throw new Error('[Sleepy] 命名空间 behaviorText 已存在，拒绝覆盖');
  }
  NS.behaviorText = Object.freeze({
    VERSION: VERSION,
    module: module,
    planOf: planOf,
    forScenario: forScenario
  });

