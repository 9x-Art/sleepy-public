  var TAG_TEXT = {
    local: '本地功能',
    api: '需要 API',
    opt: '选配能力'
  };

  /* ------------------------------ 渲染 ------------------------------ */

  function blockEl(b) {
    switch (b.t) {
      case 'p':
        return h('p', 'gz-p', b.s);

      case 'item': {
        var wrap = h('div', 'gz-item');
        wrap.appendChild(h('div', 'gz-item-n', b.n));
        wrap.appendChild(h('div', 'gz-item-d', b.d));
        return wrap;
      }

      case 'note': {
        var n = h('div', 'gz-note');
        n.appendChild(h('p', 'gz-note-p', b.s));
        return n;
      }

      case 'tag': {
        var t = h('div', 'gz-tag gz-tag-' + b.k);
        t.appendChild(h('span', 'gz-tag-k', TAG_TEXT[b.k] || b.k));
        t.appendChild(h('span', 'gz-tag-s', b.s));
        return t;
      }

      case 'li': {
        var ul = h('ul', 'gz-li');
        (b.items || []).forEach(function (x) {
          ul.appendChild(h('li', null, x));
        });
        return ul;
      }

      case 'step': {
        var st = h('div', 'gz-step');
        var head = h('div', 'gz-step-head');
        head.appendChild(h('span', 'gz-step-n', b.n));
        head.appendChild(h('span', 'gz-step-name', b.name));
        st.appendChild(head);
        if (b.path) st.appendChild(h('div', 'gz-step-path', b.path));
        if (b.d) st.appendChild(h('p', 'gz-step-d', b.d));
        if (b.note) {
          var sn = h('div', 'gz-note');
          sn.appendChild(h('p', 'gz-note-p', b.note));
          st.appendChild(sn);
        }
        if (b.tip) st.appendChild(h('p', 'gz-step-tip', b.tip));
        return st;
      }

      case 'qa': {
        var q = h('div', 'gz-qa');
        q.appendChild(h('div', 'gz-qa-q', b.q));
        q.appendChild(h('div', 'gz-qa-a', b.a));
        return q;
      }
    }
    return h('p', 'gz-p', '');
  }

  function sectionEl(sec) {
    var d = document.createElement('details');
    d.className = 'gz-sec';
    if (sec.open) d.open = true;
    /* 板块自己的马卡龙色：只写一支 --gz-c，下面所有重点元素都吃它
       （标题 / 色点 / 功能名 / 步骤圆标 / 提示块左边框 / 问答问句）。
       不逐个元素设 style —— 那样每加一种块类型就得改一处，迟早漏。 */
    if (sec.c) d.style.setProperty('--gz-c', sec.c);

    var s = document.createElement('summary');
    s.className = 'gz-sec-t';
    /* 色点：折叠着的时候，这一小颗是板块唯一的颜色线索 */
    if (sec.c) s.appendChild(h('span', 'gz-sec-dot'));
    s.appendChild(h('span', 'gz-sec-name', sec.t));
    s.appendChild(h('span', 'gz-sec-arrow'));
    d.appendChild(s);

    var body = h('div', 'gz-sec-body');
    (sec.blocks || []).forEach(function (b) {
      body.appendChild(blockEl(b));
    });
    d.appendChild(body);
    return d;
  }

  function paint(ctx) {
    var body = ctx.body;
    body.innerHTML = '';
    var root = h('div', 'gz-root');

    /* ---- 开篇：常显 ---- */
    var op = h('section', 'gz-open');
    op.appendChild(h('h1', 'gz-op-title', OPENING.title));
    op.appendChild(h('p', 'gz-op-lead', OPENING.lead));
    (OPENING.paras || []).forEach(function (p) {
      op.appendChild(h('p', 'gz-op-p', p));
    });
    var three = h('ul', 'gz-op-three');
    (OPENING.three || []).forEach(function (x) {
      three.appendChild(h('li', null, x));
    });
    op.appendChild(three);
    op.appendChild(h('p', 'gz-op-p', OPENING.tail));
    op.appendChild(h('p', 'gz-op-motto', OPENING.motto));
    root.appendChild(op);

    /* ---- 板块：折叠 ---- */
    SECTIONS.forEach(function (sec) {
      root.appendChild(sectionEl(sec));
    });

    /* ---- 结尾 ---- */
    root.appendChild(h('p', 'gz-end', 'sleepy 欢迎你的到来，和你未来的每一点微小情绪。'));

    body.appendChild(root);
  }

