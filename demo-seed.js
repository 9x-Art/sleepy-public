  /* ==================== 工具 ==================== */

  function arr(v) { return Array.isArray(v) ? v : []; }

  /* 本文件自带的 id 生成（不引 core.newId —— 语义上这是种子数据，
     不是业务记录；形状与别处一致，读起来不违和就行）。 */
  function newId(p) {
    return (p || 'x') + Date.now().toString(36) + Math.random().toString(36).slice(2, 6);
  }

  /* ==================== 注入 ==================== */

  /* ensure() —— 唯一入口。
     返回 { ok, skipped?, roomId?, charId? }；
     skipped='has-rooms' 表示「已有房间，老存档免疫」。
     只读 store.get 拿全量、整表 set 回去（深拷贝纪律：
     store.get 返回深拷贝，改完必须整表写回，不能只 set 单条）。 */
  function ensure() {
    var core = Sleepy.core;
    var store = Sleepy.store;
    if (!core || !store) return { ok: false, error: 'core/store 未就位' };

    /* 老存档免疫 + 幂等：一间房都没有才注。 */
    if (core.listSandboxes().length) return { ok: true, skipped: 'has-rooms' };

    var now = Date.now();

    /* ① 岛（isle 孤岛 = 绝对封闭，演示岛不需要群岛） */
    var sb = core.createSandbox(core.KIND_ISLE, ROOM_NAME);
    /* demo 标记回填：createSandbox 不收自定义字段，拿全量改完整表写回
       （createSandbox 返回的 sb 是原对象引用，但别依赖这一点 ——
        store.set 已经序列化落盘，走「全量读-改-写」才是稳的）。 */
    var sbAll = core.listSandboxes();
    for (var i = 0; i < sbAll.length; i++) {
      if (sbAll[i].id === sb.id) { sbAll[i].demo = true; break; }
    }
    core.saveSandboxes(sbAll);

    /* ② 小满（main 大号，upsertChar 自动盖 sandboxId 章）。
         头像留空：渲染侧 setAvatarBg/setAvatarImg 自动落 v255 幽灵。 */
    var char = core.upsertChar({
      name: CHAR_NAME,
      kind: 'main',
      gender: 'female',
      sandboxId: sb.id,
      content: CONTENT,
      speech: SPEECH,
      neverDo: NEVER_DO
    });

    /* ③ 本岛的「我」（isDefault；显式盖 demo 岛的章，别落进别的房） */
    var me = core.upsertUser({
      name: '我',
      sandboxId: sb.id,
      isDefault: true
    });

    /* ④ 关系（不知情基线：小满没有掉马戏，cognition 用默认 unaware） */
    core.addLink(char.id, me.id, 'unaware', false, sb.id);

    /* ④b 岛名册（charIds / maskIds）—— **漏了这步等于「岛里有人但名册空」**：
       activeCharOnIsland / activeUserOnIsland / defaultUserOfSandbox /
       charsOfSandbox / masksOfSandbox 全查这两个数组，桌面组件、聊天列表、
       切号器按卫兵读人的地方会大面积读空。createSandbox 建的是空名册，
       注入成员后必须回填（两个 setter 各自带校验，读全量改不冲 demo 标记）。 */
    core.setSandboxChars(sb.id, [char.id]);
    core.setSandboxMasks(sb.id, [me.id]);

    /* ⑤ 欢迎对话（createChat 同形状手写；她此时还没有页面上下文，
         不引 page-chat。tagScope 的章显式给，不靠当前指针）。 */
    var chats = arr(store.get('chats'));
    chats.push({
      id: newId('dm'),
      name: CHAR_NAME,
      characterId: char.id,
      userId: me.id,
      overrides: { temperature: null, maxTokens: null, contextMessages: null, stream: null },
      createdAt: now,
      updatedAt: now,
      sandboxId: sb.id,
      messages: [{
        id: newId('dm'),
        role: 'assistant',
        content: WELCOME,
        timestamp: now
      }]
    });
    store.set('chats', chats);

    /* ⑥ 朋友圈动态（相对时间倒序；likes/comments 空数组起步） */
    var moments = arr(store.get('moments'));
    MOMENTS.forEach(function (m) {
      moments.push({
        id: newId('mo'),
        characterId: char.id,
        name: CHAR_NAME,
        text: m.text,
        at: now - m.minutesAgo * 60000,
        sandboxId: sb.id,
        likes: [],
        comments: []
      });
    });
    store.set('moments', moments);

    /* ⑦ 功能知识（personal 世界书挂小满；8 条关键词触发，离 10 条上限留余量） */
    var books = arr(store.get('worldbooks'));
    books.push({
      id: newId('b'),
      name: BOOK_NAME,
      scope: 'personal',
      characterId: char.id,
      createdAt: now,
      updatedAt: now,
      entries: WB_ENTRIES.map(function (e) {
        return {
          id: newId('e'),
          name: e.name,
          keys: e.keys,
          always: false,
          content: e.content,
          enabled: true,
          createdAt: now,
          updatedAt: now
        };
      })
    });
    store.set('worldbooks', books);

    /* ⑧ 指针落岛（桌面 render 在此之前发生，指针必须先到位） */
    core.setActiveSandbox(sb.id);
    core.switchTo(char.id, me.id);

    return { ok: true, roomId: sb.id, charId: char.id, skipped: null };
  }

